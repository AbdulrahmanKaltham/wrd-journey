/**
 * Generates 4 random questions for testing a student on their curriculum.
 * Targets the given surahs if specified, otherwise draws from available curriculum passages.
 */
export function generateRandomExamQuestions(surahsList: string[] = []): ExamQuestion[] {
  // Normalize surah names
  const cleanSurahs = surahsList.map(s => s.trim().replace(/^سورة\s+/, '')).filter(Boolean);

  // Filter passages matching the surahs of this week
  let matchingPassages = QURAN_EXAM_PASSAGES.filter(p =>
    cleanSurahs.length === 0 || cleanSurahs.some(cs => p.surah.includes(cs) || cs.includes(p.surah))
  );

  // If we don't have at least 4 passages for these specific surahs, fallback to all passages
  if (matchingPassages.length < 4) {
    matchingPassages = [...matchingPassages, ...QURAN_EXAM_PASSAGES.filter(p => !matchingPassages.includes(p))];
  }

  // Shuffle array using Fisher-Yates
  const shuffled = [...matchingPassages];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }

  // Pick exactly 4 passages
  const selected = shuffled.slice(0, 4);

  return selected.map((p, idx) => ({
    number: idx + 1,
    prompt: `أكمل من قول الله تعالى: ﴿${p.text}﴾`,
    surah: `سورة ${p.surah}`,
    verse: p.verse,
    text: p.text,
  }));
}
